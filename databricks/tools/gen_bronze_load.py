#!/usr/bin/env python3
"""Write sql/01b_bronze_load.sql from the column list in sql/01_bronze_ddl.sql (single source of truth).

01b rebuilds bronze from every file in the Volume with read_files and an EXPLICIT schema:
  * a field absent from a file comes back as NULL instead of a missing column (COPY INTO failed on this)
  * whole numbers parse straight into DOUBLE columns (no BIGINT vs DOUBLE merge conflict)
  * CREATE OR REPLACE picks up new columns: an existing Delta table does not gain columns from CREATE TABLE IF NOT
    EXISTS, and ALTER TABLE ADD COLUMNS is not re-runnable. The Volume keeps every raw file, so a full rebuild loses
    nothing; at hackathon scale (thousands of events) it takes seconds. Switch to an incremental load at scale.
Usage: python3 gen_bronze_load.py [--check]
"""
import re
import sys
from pathlib import Path

SQL = Path(__file__).resolve().parents[1] / "sql"
ddl = (SQL / "01_bronze_ddl.sql").read_text()
body = re.search(r"CREATE TABLE IF NOT EXISTS \S+ \((.*?)\n\);", ddl, re.S).group(1)
body = re.sub(r"--[^\n]*", "", body)
cols = [tuple(c.split()[:2]) for c in (x.strip() for x in body.split(",")) if c]
raw = [(n, t) for n, t in cols if not n.startswith("_")]
assert [n for n, _ in cols if n.startswith("_")] == ["_source_file", "_ingested_at"], cols

names = ", ".join(n for n, _ in raw)
schema = ", ".join(f"{n} {t}" for n, t in raw)
out = f"""-- GENERATED by databricks/tools/gen_bronze_load.py from 01_bronze_ddl.sql. Do not edit by hand.
-- Rebuild bronze from ALL raw JSONL files in the Volume. Spark/Databricks SQL only.
-- read_files with an EXPLICIT schema: absent fields become NULL, whole numbers parse into DOUBLE columns.
-- CREATE OR REPLACE (not INSERT) so new columns appear on an existing table; the Volume keeps every raw file,
-- so the rebuild loses nothing. _ingested_at is the rebuild time.
CREATE OR REPLACE TABLE ${{catalog}}.${{schema}}.bronze_events AS
SELECT {names},
       _metadata.file_path AS _source_file, current_timestamp() AS _ingested_at
FROM read_files(
  '/Volumes/${{catalog}}/${{schema}}/${{volume}}/raw/',
  format => 'json',
  schema => '{schema}'
);
"""
target = SQL / "01b_bronze_load.sql"
if sys.argv[1:] == ["--check"]:
    sys.exit(0 if target.read_text() == out else f"{target} is stale: run {Path(__file__).name}")
target.write_text(out)
print(f"wrote {target} ({len(raw)} raw columns)")
