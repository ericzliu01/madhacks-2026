#!/usr/bin/env bash
# Concatenate the pipeline SQL into one file to paste/run in the Databricks SQL editor:
#   databricks/sql/ux_pipeline_all.sql = 00 setup, 01 bronze DDL, 01b load, 02 silver, 03 gold, 05 comments
# with ${catalog}/${schema}/${volume} filled in. 04 (AI functions, untested) is left out. Every step is safe to re-run.
# Usage: scripts/build-pipeline-sql.sh [--check]    (env CATALOG, SCHEMA, VOLUME override the defaults)
set -euo pipefail
cd "$(dirname "$0")/.."
CATALOG=${CATALOG:-workspace} SCHEMA=${SCHEMA:-ux_telemetry} VOLUME=${VOLUME:-raw_events}
OUT=databricks/sql/ux_pipeline_all.sql
gen() {
  echo "-- GENERATED by scripts/build-pipeline-sql.sh from databricks/sql/{00,01,01b,02,03,05}*.sql. Do not edit by hand."
  echo "-- Target: ${CATALOG}.${SCHEMA}, Volume ${VOLUME}. Run all statements in order; every step is safe to re-run."
  for f in 00_setup 01_bronze_ddl 01b_bronze_load 02_silver 03_gold 05_comments; do
    printf '\n-- ===================================================================== %s.sql\n' "$f"
    sed -e "s/\${catalog}/${CATALOG}/g" -e "s/\${schema}/${SCHEMA}/g" -e "s/\${volume}/${VOLUME}/g" "databricks/sql/$f.sql"
  done
}
if [[ "${1:-}" == "--check" ]]; then
  diff -q <(gen) "$OUT" >/dev/null || { echo "$OUT is stale: run scripts/build-pipeline-sql.sh"; exit 1; }
  echo "$OUT up to date"
else
  gen > "$OUT"; echo "wrote $OUT"
fi
